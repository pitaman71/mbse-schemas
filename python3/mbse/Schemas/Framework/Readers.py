"""Readers: the read-only view of each `Visitors.OfX`.

`Readers.OfX` holds the reading members of `Visitors.OfX` only. It is a type, not a second implementation: code that
must not write (evaluators, validators, comparison, codegen's readers) takes a `Readers.OfX`, so that a type checker
enforces it. Every `Visitors.OfX` is a `Readers.OfX`.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Iterator, Mapping
from typing import TYPE_CHECKING, Any, Generic, Protocol, Self, TypeVar

if TYPE_CHECKING:
    from . import Schemas

__all__ = ["OfScalar", "OfAny", "OfProperty", "OfObject", "OfAdjacency", "OfEntry", "OfUnion", "OfIntersection", "OfContainer", "OfIterator",
           "OfPattern"]

T = TypeVar("T", int, float, str, bool, bytes)
V = TypeVar("V")

Read = Callable[[V], V]
"""A reading callback: it takes a reader and returns it."""


class OfScalar(Protocol, Generic[T]):
    def as_schema(self) -> Schemas.OfScalar.Data: ...

    def get(self) -> T | None: ...

    def __int__(self) -> int: ...

    def __float__(self) -> float: ...

    def __str__(self) -> str: ...

    def __bool__(self) -> bool: ...

    def __bytes__(self) -> bytes: ...


class OfAny(Protocol):
    def as_schema(self) -> Schemas.OfAny.Data: ...

    def as_scalar(self, cb: Read[OfScalar[Any]]) -> Self: ...

    def as_object(self, cb: Read[OfObject]) -> Self: ...

    def as_union(self, cb: Read[OfUnion]) -> Self: ...

    def as_intersection(self, cb: Read[OfIntersection]) -> Self: ...

    def as_container(self, cb: Read[OfContainer]) -> Self: ...


class OfContainer(Protocol):
    def as_schema(self) -> Schemas.OfContainer.Data: ...

    def __len__(self) -> int: ...

    def at(self, index: Any) -> OfAny: ...

    def as_ordered(self, cb: Read[OfIterator]) -> Self: ...

    def as_dict(self, cb: Read[Mapping[Any, OfAny]]) -> Self: ...

    def as_entries(self, cb: Read[Iterator[tuple[Any, OfAny]]]) -> Self: ...


class OfIterator(Protocol):
    def first(self) -> Self: ...

    def last(self) -> Self: ...

    def next(self) -> Self: ...

    def prev(self) -> Self: ...

    def index(self) -> Any: ...

    def as_item(self, cb: Read[OfAny]) -> Self: ...


class OfProperty(Protocol):
    def as_schema(self) -> Schemas.OfProperty.Data: ...

    def as_value(self, cb: Read[OfAny]) -> Self: ...

    def as_scalar(self, cb: Read[OfScalar[Any]]) -> Self: ...

    def as_object(self, cb: Read[OfObject]) -> Self: ...

    def get(self) -> int | float | str | bool | bytes | None: ...

    def __int__(self) -> int: ...

    def __float__(self) -> float: ...

    def __str__(self) -> str: ...

    def __bool__(self) -> bool: ...

    def __bytes__(self) -> bytes: ...


class OfObject(Protocol):
    def as_schema(self) -> Schemas.OfObject.Data: ...

    @property
    def as_properties(self) -> Iterable[OfProperty]: ...

    def as_adjacencies(self, cb: Read[OfAdjacency]) -> Self: ...

    def __getattr__(self, name: str) -> Any: ...


class OfAdjacency(Iterable["OfEntry"], Protocol):
    def as_schema(self) -> Schemas.OfAdjacency.Data: ...

    def __iter__(self) -> Iterator[OfEntry]: ...

    def as_iterable(self, cb: Read[Iterator[OfEntry]]) -> Self: ...


class OfEntry(Protocol):
    def as_schema(self) -> Schemas.OfEntry.Data: ...

    def __getattr__(self, name: str) -> Any: ...


class OfUnion(Protocol):
    def as_schema(self) -> Schemas.OfUnion.Data: ...

    def __getattr__(self, name: str) -> Any: ...


class OfIntersection(Protocol):
    def as_schema(self) -> Schemas.OfIntersection.Data: ...

    def __getattr__(self, name: str) -> Any: ...


class OfPattern(Protocol):
    def as_schema(self) -> Schemas.OfPattern.Data: ...

    def __getattr__(self, name: str) -> Any: ...
